const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
  const errs = []; pg.on('pageerror', e => errs.push(e.message));
  await pg.goto('http://localhost:8765/index.html'); await pg.waitForSelector('#pn-0');
  await pg.waitForFunction(() => PHOTO_CATS.length > 0);
  await pg.fill('#pn-0', 'Ann'); await pg.press('#pn-0', 'Enter'); await pg.fill('#pn-1', 'Ben');
  await pg.click('#mixCats'); await pg.click('#start'); await pg.waitForSelector('#mus');
  console.log('board music button:', (await pg.textContent('#mus')).trim());
  await pg.click('#board .cell >> nth=0'); await pg.click('#board .cell.target >> nth=0');
  await pg.click('#firstA'); await pg.waitForFunction(() => D && D.phase === 'run', null, { timeout: 6000 });
  await pg.waitForTimeout(1500);
  const nodes = () => pg.evaluate(() => ({ state: ac && ac.state, t: ac && ac.currentTime.toFixed(2) }));
  console.log('running duel, audio:', JSON.stringify(await nodes()));
  await pg.evaluate(() => { D.time[D.active] = 9000; }); await pg.waitForTimeout(800);
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(300);
  console.log('paused phase:', await pg.evaluate(() => D.phase));
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(500);
  console.log('resumed phase:', await pg.evaluate(() => D.phase));
  await pg.keyboard.press('m'); await pg.waitForTimeout(200); console.log('after M, music on:', await pg.evaluate(() => music.on));
  await pg.keyboard.press('m'); await pg.waitForTimeout(200); console.log('after M again, music on:', await pg.evaluate(() => music.on));
  await pg.evaluate(() => { D.time[D.active] = 50; }); await pg.waitForFunction(() => D && D.phase === 'done', null, { timeout: 4000 });
  console.log('duel ended:', (await pg.textContent('#ov h2')).trim());
  console.log('errors:', errs.length ? errs : 'none');
  await b.close();
})().catch(e => { console.error('TEST FAILED:', e.message); process.exit(1); });
